//! Embeds every icon SVG into the crate, so icons need no files at runtime.

use std::{env, fmt::Write as _, fs, path::Path};

struct Set {
    /// Name of the generated static.
    ident: &'static str,
    /// Folder, relative to the workspace root.
    dir: &'static str,
}

const SETS: &[Set] = &[
    Set {
        ident: "GODOT",
        dir: "third_party/godot/editor/icons",
    },
    Set {
        ident: "AT",
        dir: "third_party/at-icons/icons",
    },
    Set {
        ident: "BRAND",
        dir: "branding",
    },
    Set {
        ident: "UI",
        dir: "crates/oddity_icons/ui",
    },
];

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let root = Path::new(&manifest_dir)
        .join("../..")
        .canonicalize()
        .unwrap();
    let mut out = String::from("// @generated by build.rs. Do not edit.\n\n");

    for set in SETS {
        let dir = root.join(set.dir);
        println!("cargo::rerun-if-changed={}", dir.display());

        let mut entries: Vec<(String, String)> = fs::read_dir(&dir)
            .unwrap_or_else(|e| panic!("cannot read icon folder {}: {e}", dir.display()))
            .filter_map(|entry| {
                let path = entry.ok()?.path();
                if path.extension()? != "svg" {
                    return None;
                }
                let name = path.file_stem()?.to_str()?.to_owned();
                Some((name, path.display().to_string().replace('\\', "/")))
            })
            .collect();
        // Sorted so lookups can use a binary search.
        entries.sort();

        writeln!(out, "pub(crate) static {}: &[(&str, &str)] = &[", set.ident).unwrap();
        for (name, path) in &entries {
            writeln!(out, "    ({name:?}, include_str!({path:?})),").unwrap();
        }
        out.push_str("];\n\n");
    }

    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("icons.rs");
    fs::write(dest, out).unwrap();
}
